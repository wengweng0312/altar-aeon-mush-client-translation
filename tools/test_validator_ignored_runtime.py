"""An ignored test-generated worker log must not contaminate source validation."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
runtime_log = ROOT / "src/mush-z/worlds/plugins/translation_bridge/translation_worker.log"
runtime_log.write_text("generated by isolated regression test\n", encoding="utf-8")
try:
    ignored = subprocess.run(
        ["git", "-C", str(ROOT), "check-ignore", "--quiet", str(runtime_log)],
        check=False,
    )
    assert ignored.returncode == 0, "fixture must remain covered by .gitignore"
    result = subprocess.run(
        [sys.executable, str(ROOT / "tools/validate_source.py")],
        check=False,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    assert result.returncode == 0, result.stdout
    assert "SOURCE_VALIDATION_OK" in result.stdout, result.stdout
finally:
    runtime_log.unlink(missing_ok=True)

print("VALIDATOR_IGNORED_RUNTIME_OK ignored_log=no_source_contamination")
